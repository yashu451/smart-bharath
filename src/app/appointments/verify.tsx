import React, { useEffect, useState } from 'react';
import {
  View,
  Text,
  TouchableOpacity,
  SafeAreaView,
  ScrollView,
  StatusBar,
  ActivityIndicator,
  Image,
} from 'react-native';
import { useRouter, useLocalSearchParams } from 'expo-router';
import { appointmentApi } from '@/services/api';
import { formatISTDate } from '@/utils/date-time';

export default function AppointmentVerifyScreen() {
  const router = useRouter();
  const params = useLocalSearchParams();

  const tokenParam = (params.token as string) || (params.id as string) || '';

  const [isLoading, setIsLoading] = useState(true);
  const [verificationResult, setVerificationResult] = useState<any>(null);
  const [errorMessage, setErrorMessage] = useState<string | null>(null);

  useEffect(() => {
    let isMounted = true;

    async function runVerification() {
      if (!tokenParam) {
        setIsLoading(false);
        setErrorMessage('No appointment verification token or reference ID provided.');
        return;
      }

      setIsLoading(true);
      setErrorMessage(null);

      try {
        const res = await appointmentApi.verifyAppointment(tokenParam);
        if (isMounted) {
          if (res.success && res.appointment) {
            setVerificationResult(res);
          } else {
            setErrorMessage(res.message || 'Appointment record not found or verification token is invalid.');
          }
        }
      } catch (err: any) {
        if (isMounted) {
          setErrorMessage(err.message || 'Unable to connect to verification server. Please verify your connection.');
        }
      } finally {
        if (isMounted) {
          setIsLoading(false);
        }
      }
    }

    runVerification();

    return () => {
      isMounted = false;
    };
  }, [tokenParam]);

  const appt = verificationResult?.appointment;
  const isValid = verificationResult?.isValid === true;
  const isCancelled = appt?.isCancelled || appt?.status === 'Cancelled';

  return (
    <SafeAreaView style={{ flex: 1, backgroundColor: '#E6F0E8' }}>
      <StatusBar barStyle="dark-content" backgroundColor="#E6F0E8" />

      {/* Header bar */}
      <View className="px-6 py-4 flex-row items-center border-b border-[#CADDCB] bg-[#EDF5EE]">
        <View className="max-w-xl w-full mx-auto flex-row items-center">
          <TouchableOpacity
            onPress={() => router.replace('/home')}
            className="w-12 h-12 rounded-2xl bg-[#E0EDE1] border border-[#CADDCB] justify-center items-center mr-4 shadow-xs"
            activeOpacity={0.7}
          >
            <Text className="text-[#14532D] font-black text-xl">←</Text>
          </TouchableOpacity>
          <View className="flex-1">
            <Text className="text-xl font-black text-[#14532D]">Gatepass Verification</Text>
            <Text className="text-xs font-bold text-[#4B6350] uppercase tracking-widest mt-0.5">
              Smart Bharat Citizen Portal
            </Text>
          </View>
        </View>
      </View>

      <ScrollView
        style={{ flex: 1 }}
        contentContainerStyle={{
          padding: 24,
          paddingBottom: 130,
          alignItems: 'center',
        }}
      >
        <View className="w-full max-w-xl items-center">
          {isLoading ? (
            <View className="py-24 items-center justify-center">
              <ActivityIndicator size="large" color="#14532D" />
              <Text className="text-sm font-bold text-[#14532D] mt-3">
                Verifying digital gatepass token...
              </Text>
              <Text className="text-xs text-slate-500 mt-1">
                Querying Smart Bharat MongoDB database
              </Text>
            </View>
          ) : errorMessage || !appt ? (
            /* Unverified / Unavailable State */
            <View
              style={{
                shadowColor: '#14532D',
                shadowOffset: { width: 0, height: 4 },
                shadowOpacity: 0.05,
                shadowRadius: 10,
                elevation: 2,
              }}
              className="w-full bg-[#F3F8F4] border border-red-200 rounded-3xl p-8 items-center text-center my-4"
            >
              <View className="w-20 h-20 rounded-3xl bg-red-50 border border-red-200 justify-center items-center mb-4">
                <Text className="text-4xl">⚠️</Text>
              </View>

              <Text className="text-2xl font-black text-red-700 tracking-tight text-center">
                Gatepass Record Unavailable
              </Text>

              <Text className="text-sm font-medium text-slate-600 text-center mt-2 leading-relaxed">
                {errorMessage ||
                  'This gatepass token is either invalid, expired, or was not generated by an authenticated Smart Bharat user session.'}
              </Text>

              <View className="w-full bg-[#EDF5EE] border border-[#CADDCB] rounded-2xl p-4 mt-6">
                <Text className="text-xs font-bold text-[#4B6350] text-center">
                  Scanned Reference: {tokenParam || 'None'}
                </Text>
              </View>

              <TouchableOpacity
                onPress={() => router.replace('/home')}
                style={{ minHeight: 52 }}
                className="mt-6 w-full py-4 px-6 bg-[#14532D] rounded-2xl justify-center items-center shadow-xs"
                activeOpacity={0.8}
              >
                <Text className="text-white text-base font-black uppercase tracking-wider">
                  Return to Dashboard
                </Text>
              </TouchableOpacity>
            </View>
          ) : (
            /* Verified Gatepass Details Card */
            <View className="w-full items-center">
              {/* Status Header Badge */}
              <View
                className={`w-20 h-20 rounded-3xl justify-center items-center mb-3.5 border ${
                  isCancelled
                    ? 'bg-red-50 border-red-200'
                    : 'bg-[#ECFDF5] border-[#A7F3D0]'
                }`}
              >
                <Text className="text-4xl">{isCancelled ? '✕' : '✓'}</Text>
              </View>

              <Text
                className={`text-2xl font-black tracking-tight text-center ${
                  isCancelled ? 'text-red-700' : 'text-[#14532D]'
                }`}
              >
                {isCancelled
                  ? 'Appointment Cancelled'
                  : 'Valid Scheduled Appointment'}
              </Text>

              <View
                className={`mt-2 px-3.5 py-1 rounded-full border ${
                  isCancelled
                    ? 'bg-red-50 border-red-200'
                    : 'bg-[#ECFDF5] border-[#A7F3D0]'
                }`}
              >
                <Text
                  className={`text-xs font-black uppercase tracking-wider ${
                    isCancelled ? 'text-red-700' : 'text-[#10B981]'
                  }`}
                >
                  {isCancelled ? 'Status: Cancelled' : 'Status: Confirmed Active'}
                </Text>
              </View>

              {/* Main Ticket Card */}
              <View
                style={{
                  shadowColor: '#14532D',
                  shadowOffset: { width: 0, height: 6 },
                  shadowOpacity: 0.08,
                  shadowRadius: 16,
                  elevation: 3,
                }}
                className="bg-[#F3F8F4] border border-[#CADDCB] rounded-3xl w-full mt-6 overflow-hidden"
              >
                {/* Header Banner in Forest Green */}
                <View className="bg-[#14532D] px-6 py-4.5 flex-row items-center">
                  <Text className="text-2xl mr-3">🛂</Text>
                  <View className="flex-1">
                    <Text className="text-[10px] font-black text-emerald-200 uppercase tracking-widest">
                      Digital Gatepass Ticket
                    </Text>
                    <Text className="text-base font-black text-white mt-0.5" numberOfLines={1}>
                      {appt.department}
                    </Text>
                  </View>
                </View>

                {/* Body Details */}
                <View className="p-6 space-y-3.5">
                  <View className="flex-row justify-between items-center pb-3 border-b border-[#CADDCB]">
                    <View className="flex-1 pr-2">
                      <Text className="text-xs font-bold text-slate-400 uppercase tracking-wider">
                        Booking ID
                      </Text>
                      <Text className="text-sm font-black text-[#14532D] mt-0.5">
                        {appt.bookingId}
                      </Text>
                    </View>
                    <View className="items-end">
                      <Text className="text-xs font-bold text-slate-400 uppercase tracking-wider">
                        Scheduled Slot
                      </Text>
                      <Text className="text-sm font-black text-[#10B981] mt-0.5">
                        {appt.time || 'Office Hours'}
                      </Text>
                    </View>
                  </View>

                  <View className="py-1">
                    <Text className="text-xs font-bold text-slate-400 uppercase tracking-wider">
                      Requested Service
                    </Text>
                    <Text className="text-base font-black text-[#14532D] mt-0.5">
                      {appt.service}
                    </Text>
                  </View>

                  <View className="py-1">
                    <Text className="text-xs font-bold text-slate-400 uppercase tracking-wider">
                      Office Location
                    </Text>
                    <Text className="text-sm font-semibold text-slate-800 mt-0.5">
                      {appt.location}
                    </Text>
                  </View>

                  <View className="py-1">
                    <Text className="text-xs font-bold text-slate-400 uppercase tracking-wider">
                      Scheduled Date (IST)
                    </Text>
                    <Text className="text-base font-black text-[#14532D] mt-0.5">
                      {appt.date ? formatISTDate(appt.date) : 'N/A'} (Indian Standard Time)
                    </Text>
                  </View>

                  {appt.purpose ? (
                    <View className="py-1">
                      <Text className="text-xs font-bold text-slate-400 uppercase tracking-wider">
                        Citizen Remarks
                      </Text>
                      <Text className="text-sm font-medium text-slate-700 mt-0.5">
                        {appt.purpose}
                      </Text>
                    </View>
                  ) : null}

                  {/* QR Code representation if present */}
                  {appt.qrCodeDataUrl ? (
                    <View className="mt-2 p-4 bg-[#EDF5EE] border border-dashed border-[#CADDCB] rounded-2xl items-center">
                      <Image
                        source={{ uri: appt.qrCodeDataUrl }}
                        style={{ width: 140, height: 140, borderRadius: 12 }}
                        resizeMode="contain"
                      />
                      <Text className="text-[11px] font-bold text-[#14532D] mt-2">
                        Official Scannable Verification Pass
                      </Text>
                    </View>
                  ) : null}

                  {/* Important Internal Verification Disclaimer */}
                  <View className="bg-[#FFFBEB] border border-[#FDE68A] rounded-2xl p-4 mt-2">
                    <View className="flex-row items-center mb-1.5">
                      <Text className="text-base mr-2">🛡️</Text>
                      <Text className="text-xs font-black text-amber-900 uppercase tracking-wider">
                        Internal Verification Notice
                      </Text>
                    </View>
                    <Text className="text-[11px] text-amber-800 leading-relaxed font-medium">
                      This digital pass confirms appointment scheduling within the Smart Bharat portal. Official office integration is not yet active; this serves as Smart Bharat's internal citizen gatepass and does not claim official government reception by the physical department.
                    </Text>
                  </View>
                </View>
              </View>

              {/* Action Buttons */}
              <View className="w-full mt-6 gap-3.5">
                <TouchableOpacity
                  onPress={() => router.push('/appointments/my-appointments' as any)}
                  style={{ minHeight: 56 }}
                  className="w-full py-4.5 px-6 bg-[#14532D] rounded-2xl justify-center items-center shadow-xs"
                  activeOpacity={0.85}
                >
                  <Text className="text-white text-base font-black uppercase tracking-wider">
                    View in My Appointments →
                  </Text>
                </TouchableOpacity>

                <TouchableOpacity
                  onPress={() => router.replace('/home')}
                  style={{ minHeight: 52 }}
                  className="w-full py-4 px-6 border border-[#CADDCB] bg-[#EDF5EE] rounded-2xl justify-center items-center shadow-xs"
                  activeOpacity={0.7}
                >
                  <Text className="text-[#14532D] text-sm font-black uppercase tracking-wider">
                    Return to Dashboard
                  </Text>
                </TouchableOpacity>
              </View>
            </View>
          )}
        </View>
      </ScrollView>
    </SafeAreaView>
  );
}

